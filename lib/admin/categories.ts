import { prisma } from "@/lib/db";
import { slugify } from "@/lib/format";
import { categoryBannerUrl } from "@/lib/admin/images";
import type { AdminResult } from "@/lib/admin/catalogue-admin";
import { CATEGORY_ART_KEYS, type CategoryArtKey } from "@/data/types";

/**
 * Category mutations for the admin dashboard.
 *
 * A category carries a `priceMin` / `priceMax` envelope that the storefront
 * shows on the category page. Those two numbers are derived from the products
 * inside the category, so they are recomputed whenever a product is added,
 * moved or removed.
 */

/** Everything the dashboard needs to create or update a category. */
export type CategoryInput = {
  name: string;
  tagline: string;
  description: string;
  artKey: string;
  /** Optional uploaded banner URL. Empty uses generated category artwork. */
  bannerImage: string;
  /** `label: value` per line. */
  specs: string;
  sortOrder: number;
};

function parseSpecs(value: string): { label: string; value: string; position: number }[] {
  return value
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter(Boolean)
    .map((line, position) => {
      const separator = line.indexOf(":");
      return separator < 0
        ? { label: line, value: "", position }
        : {
            label: line.slice(0, separator).trim(),
            value: line.slice(separator + 1).trim(),
            position,
          };
    })
    .filter((spec) => spec.label.length > 0);
}

/**
 * Recomputes the price envelope of every category from its products.
 *
 * Called after any product write so the storefront never shows a stale range.
 */
export async function refreshCategoryPriceRanges(): Promise<void> {
  const categories = await prisma.category.findMany({
    select: { id: true },
  });

  for (const category of categories) {
    const prices = await prisma.productPrice.findMany({
      where: { product: { categoryId: category.id } },
      select: { price: true },
      orderBy: { price: "asc" },
    });

    if (!prices.length) {
      await prisma.category.update({
        where: { id: category.id },
        data: { priceMin: 0, priceMax: 0 },
      });
      continue;
    }

    const first = prices[0].price;
    const last = prices[prices.length - 1].price;

    await prisma.category.update({
      where: { id: category.id },
      data: { priceMin: first, priceMax: last },
    });
  }
}

/** Builds a slug that no other category is using. */
async function buildSlug(base: string, excludeId?: string): Promise<string> {
  const root = slugify(base) || "category";
  let candidate = root;
  let counter = 2;

  for (;;) {
    const existing = await prisma.category.findUnique({
      where: { slug: candidate },
      select: { id: true },
    });
    if (!existing || existing.id === excludeId) return candidate;
    candidate = `${root}-${counter}`;
    counter += 1;
  }
}

/** Validates the category fields before anything is written. */
export function validateCategory(input: CategoryInput): string[] {
  const errors: string[] = [];
  if (!input.name.trim()) errors.push("Name is required.");
  if (!input.tagline.trim()) errors.push("Tagline is required.");
  if (!input.description.trim()) errors.push("Description is required.");
  if (!CATEGORY_ART_KEYS.includes(input.artKey as CategoryArtKey)) {
    errors.push("Choose a valid illustration style.");
  }
  if (input.bannerImage.trim()) {
    const url = input.bannerImage.trim();
    const isLocalPath = url.startsWith("/") && !url.startsWith("//");
    let isHttpUrl = false;
    try {
      isHttpUrl = ["http:", "https:"].includes(new URL(url).protocol);
    } catch {
      // Keep the validation message below for invalid URLs.
    }
    if (!isLocalPath && !isHttpUrl) errors.push("Category image must be a local path or an http(s) URL.");
  }
  const labels = parseSpecs(input.specs).map((spec) => spec.label.toLowerCase());
  if (new Set(labels).size !== labels.length) {
    errors.push("Specification labels must be unique.");
  }
  if (!Number.isInteger(input.sortOrder) || input.sortOrder < 0) {
    errors.push("Sort order cannot be negative.");
  }
  return errors;
}

/** Creates a category. The id is generated by Postgres. */
export async function createCategory(
  input: CategoryInput,
): Promise<AdminResult<{ id: string; slug: string }>> {
  const errors = validateCategory(input);
  if (errors.length) {
    return { ok: false, errors: errors.map((message) => ({ message })) };
  }

  const slug = await buildSlug(input.name);
  const artKey = input.artKey.trim() as CategoryArtKey;

  const category = await prisma.$transaction(async (tx) => {
    const created = await tx.category.create({
      data: {
        name: input.name.trim(),
        slug,
        tagline: input.tagline.trim(),
        description: input.description.trim(),
        artKey,
        priceMin: 0,
        priceMax: 0,
        bannerImage: input.bannerImage.trim() || categoryBannerUrl(artKey, 210, input.name.trim(), input.tagline.trim()),
        sortOrder: input.sortOrder,
      },
      select: { id: true, slug: true },
    });
    const specs = parseSpecs(input.specs);
    if (specs.length) {
      await tx.categorySpec.createMany({
        data: specs.map((spec) => ({ categoryId: created.id, ...spec })),
      });
    }
    return created;
  });

  return { ok: true, value: category };
}

/** Updates a category and refreshes its banner and price envelope. */
export async function updateCategory(
  id: string,
  input: CategoryInput,
): Promise<AdminResult<{ id: string; slug: string }>> {
  const errors = validateCategory(input);
  if (errors.length) {
    return { ok: false, errors: errors.map((message) => ({ message })) };
  }

  const existing = await prisma.category.findUnique({
    where: { id },
    select: { id: true, bannerImage: true },
  });
  if (!existing) {
    return { ok: false, errors: [{ message: "That category no longer exists." }] };
  }

  const slug = await buildSlug(input.name, id);
  const artKey = input.artKey.trim() as CategoryArtKey;
  const submittedBanner = input.bannerImage.trim();
  const bannerImage =
    !submittedBanner ||
    (existing.bannerImage.startsWith("/api/product-image/") && submittedBanner === existing.bannerImage)
      ? categoryBannerUrl(artKey, 210, input.name.trim(), input.tagline.trim())
      : submittedBanner;

  const category = await prisma.$transaction(async (tx) => {
    const updated = await tx.category.update({
      where: { id },
      data: {
        name: input.name.trim(),
        slug,
        tagline: input.tagline.trim(),
        description: input.description.trim(),
        artKey,
        bannerImage,
        sortOrder: input.sortOrder,
      },
      select: { id: true, slug: true },
    });
    await tx.categorySpec.deleteMany({ where: { categoryId: id } });
    const specs = parseSpecs(input.specs);
    if (specs.length) {
      await tx.categorySpec.createMany({
        data: specs.map((spec) => ({ categoryId: id, ...spec })),
      });
    }
    return updated;
  });

  await refreshCategoryPriceRanges();

  return { ok: true, value: category };
}

/**
 * Deletes a category.
 *
 * A category that still holds products cannot be deleted - products point at
 * their category with a `Restrict` rule, so the delete is refused and the
 * operator is told how many products need to move first.
 */
export async function deleteCategory(id: string): Promise<AdminResult<null>> {
  const existing = await prisma.category.findUnique({
    where: { id },
    select: { id: true, name: true, _count: { select: { products: true } } },
  });
  if (!existing) {
    return { ok: false, errors: [{ message: "That category no longer exists." }] };
  }

  if (existing._count.products > 0) {
    return {
      ok: false,
      errors: [
        {
          message: `${existing.name} still has ${existing._count.products} product(s). Move or delete them first.`,
        },
      ],
    };
  }

  await prisma.category.delete({ where: { id } });
  return { ok: true, value: null };
}
